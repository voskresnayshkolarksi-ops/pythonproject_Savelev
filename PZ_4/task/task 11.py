# Дана арифметическая прогрессия а1=1, а2=4, а3=7, а4 =10, а5 =13, ... Составить
# программу, которая каждый элемент прогрессии разделит на 2 и результат округлит
# до ближайшего целого.
N = int(input("Введите количество элементов прогрессии (N): "))

a = 1
i = 1

print("\nРезультаты обработки элементов:")

while i <= N:
    d = a / 2
    rounded = round(d)

    print(f"a{i} = {a}  =>  округлили: {rounded}")

    a += 3
    i += 1
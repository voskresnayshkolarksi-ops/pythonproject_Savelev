#  Дано множество A из N точек (точки заданы своими координатами х, у). Среди всех
# точек этого множества, лежащих во второй четверти, найти точку, наиболее
# удаленную от начала координат. Если таких точек нет, то вывести точку с нулевыми
# координатами.
# Расстояние R между точками с координатами (x1, y 1) и (x 2, у2) вычисляется по формуле:
# R = √(x2 – x1)2 + (у2 – y1)2.
# Для хранения данных о каждом наборе точек следует использовать по два списка: первый
# список для хранения абсцисс, второй — для хранения ординат.

lst_X = []
lst_Y = []
N = int(input("Введите количество точек: "))
i = 0

while i < N:
    lst_X.append(float(input(f"Введите значение X{i + 1} координат: ")))
    lst_Y.append(float(input(f"Введите значение Y{i + 1} координат: ")))
    i += 1

max_R = -1
ans_X = 0
ans_Y = 0
i = 0

while i < N:
    if lst_X[i] < 0 and lst_Y[i] > 0:
        R = ((lst_X[i] - 0) ** 2 + (lst_Y[i] - 0) ** 2) ** 0.5
        if R > max_R:
            max_R = R
            ans_X = lst_X[i]
            ans_Y = lst_Y[i]
    i += 1

print("Искомая точка:", ans_X, ans_Y)

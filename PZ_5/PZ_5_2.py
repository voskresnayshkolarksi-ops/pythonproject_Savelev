# Описать функцию Mean(X, Y, AMean, GMean), вычисляющую среднее арифметическое AMean = (X+Y)/2 и среднее геометрическое GMean = y/X Y двух положительных чисел X и Y (X и Y — входные, AMean и GMean — выходные
# параметры вещественного типа). С помощью этой функции найти среднее
# арифметическое и среднее геометрическое для пар (A, B), (A, C), (A, D), если даны A, B, C, D.

def Mean(X, Y):
    AMean = (X + Y) / 2
    GMean = (Y / X) * Y
    return AMean, GMean

print("Введите 4 положительных числа через пробел")
A, B, C, D = map(float, input().split())

am_ab, gm_ab = Mean(A, B)
print(f"Пара (А,B).Среднее арифметическое {am_ab:.3f}, среднее геометрическое {gm_ab:.3f}")

am_bc, gm_bc = Mean(B, C)
print(f"Пара (B,C).Среднее арифметическое {am_bc:.3f}, среднее геометрическое {gm_bc:.3f}")

am_ac, gm_ac = Mean(A, C)
print(f"Пара (А,C).Среднее арифметическое {am_ac:.3f}, среднее геометрическое {gm_ac:.3f}")


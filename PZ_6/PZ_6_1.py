# Дан список размера N и целые числа K и L (1 < K ≤ L ≤ N). Найти среднее
# арифметическое всех элементов списка, кроме элементов с номерами от K до L включительно.

lst_start = []
N = int(input("Введите число целых чисел: "))
K = int(input("Введите К (1 < K ≤ L ≤ N):"))
L = int(input("Введите L: "))
i = 0

while i < N:
    lst_start.append(1 + i)
    i += 1

lst = lst_start[:K - 1] + lst_start[L:]

print("Сумма списка равна", sum(lst))


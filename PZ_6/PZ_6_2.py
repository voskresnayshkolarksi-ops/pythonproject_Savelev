# Даны списки A и B одинакового размера N. Поменять местами их содержимое и
# вывести вначале элементы преобразованного списка A, а затем — элементы
# преобразованного списка B.


lst_A = []
lst_B = []
N = int(input("Введите колическтва значений в списке: "))
i = 0

while i < N:
    lst_A.append(input("Введите элемент списка: "))
    i += 1

lst_B = lst_A[::-1]

print("Первоначальный список",lst_A)
print("Обратный список",lst_B)